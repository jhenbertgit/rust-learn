import fs from "node:fs";
import YAML from "yaml";
const wf = YAML.parse(fs.readFileSync(".github/workflows/pages.yml", "utf8"));
const jobs = Object.keys(wf.jobs || {});
console.log("name:", wf.name);
console.log("triggers:", Object.keys(wf.on || wf.true || {}).join(", "));
console.log("permissions:", JSON.stringify(wf.permissions));
console.log("jobs:", jobs.join(", "));
const steps = wf.jobs["verify-and-build"].steps.map(s => (s.name || s.uses));
console.log("build steps:");
steps.forEach((s,i)=>console.log("  " + (i+1) + ". " + s));
const deployJob = wf.jobs.deploy;
console.log("deploy needs:", deployJob.needs, "| environment:", deployJob.environment?.name, "| env url:", deployJob.environment?.url);
const problems = [];
if (!wf.jobs["verify-and-build"]) problems.push("missing verify-and-build job");
if (!wf.jobs.deploy) problems.push("missing deploy job");
if (deployJob?.needs !== "verify-and-build") problems.push("deploy does not depend on the build job");
if (wf.permissions?.pages !== "write") problems.push("missing pages: write permission");
if (wf.permissions?.["id-token"] !== "write") problems.push("missing id-token: write permission");
const usesList = jobs.flatMap(j => (wf.jobs[j].steps||[]).map(s=>s.uses).filter(Boolean));
console.log("\nuses:", usesList.join(" | "));
const upload = (wf.jobs["verify-and-build"].steps||[]).find(s => String(s.uses||"").includes("upload-pages-artifact"));
if (!upload) problems.push("no upload-pages-artifact step");
else if (upload.with?.path !== "dist") problems.push("artifact path is not dist");
const deployStep = (deployJob.steps||[]).find(s => String(s.uses||"").includes("deploy-pages"));
if (!deployStep) problems.push("no deploy-pages step");
if (!deployStep?.id) problems.push("deploy step is missing an id for the page_url output");
console.log(problems.length ? "\nPROBLEMS:\n  " + problems.join("\n  ") : "\nworkflow structure looks valid");
